// Requires an explicit, isolated fixture; never defaults to the live server.
const {chromium}=require(process.env.WMT_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const config=JSON.parse(require('node:fs').readFileSync(process.env.WMT_ROUTINE_FIXTURE));
assert(config.base.startsWith('http://127.0.0.1:')&&config.members?.length===3);
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[],notices=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',async dialog=>{notices.push(dialog.message());await dialog.accept();});
  await page.goto(config.base);await page.waitForFunction(()=>typeof currentUsers!=='undefined'&&currentUsers.length>0);
  await page.evaluate(id=>setDemoActor(id),config.manager);
  await page.locator('#orgTab').click();await page.locator('#orgRoutineTab').click();
  await page.locator('#orgRoutine>.org-panel-action button').click();
  assert.equal(await page.locator('#routineAssignment').count(),0);
  assert.equal(await page.locator('#routinePosition').count(),0);
  const firstName=await page.evaluate(id=>currentUsers.find(u=>u.id===id).name,config.members[0]);
  await page.locator('#routineOwnerSearch').fill(firstName);await page.locator('#routineOwnerAll').click();
  assert.equal(await page.locator('#routineOwnerOptions input:checked').count(),1);
  await page.locator('#routineOwnerSearch').fill('不存在的搜索结果');
  assert.equal(await page.locator('#routineOwnerOptions input:checked').count(),1);
  await page.locator('#routineOwnerSearch').fill('');await page.locator('#routineOwnerClear').click();
  for(const id of config.members)await page.locator('#routineOwnerOptions input[value="'+id+'"]').check();
  assert((await page.locator('#routineOwnerSelection').textContent()).includes('已选 3 人'));
  await page.locator('#routineTitle').fill('[人员演练]每周检查');
  await page.locator('#routineNode').selectOption(String(config.domain));
  await page.locator('#routineDeliverable').fill('每名员工自己的检查记录');await page.locator('#routineHours').fill('4.5');
  await page.locator('#routineForm button[type="submit"]').click();await page.locator('#routineDialog').waitFor({state:'hidden'});
  await page.waitForFunction(()=>window.routineTemplates?.some(t=>t.title==='[人员演练]每周检查'));
  const template=await page.evaluate(()=>window.routineTemplates.find(t=>t.title==='[人员演练]每周检查'));
  assert.equal(template.assignment_type,'people');assert.equal(template.owner_id,null);assert.equal(template.target_count,3);
  assert.deepEqual(template.owner_ids.slice().sort((a,b)=>a-b),config.members.slice().sort((a,b)=>a-b));
  assert.deepEqual(template.target_members.map(u=>u.id).sort((a,b)=>a-b),config.members.slice().sort((a,b)=>a-b));
  const card=page.locator('.routine-template-row').filter({hasText:'[人员演练]每周检查'});
  assert((await card.textContent()).includes('3 人'));
  await card.getByRole('button',{name:'补生成本周任务'}).click();await page.locator('#actionConfirmSubmit').click();
  await page.waitForFunction(id=>currentTasks.filter(t=>t.parent_template_id===id).length===3,template.id);
  let tasks=await page.evaluate(id=>currentTasks.filter(t=>t.parent_template_id===id),template.id);
  assert(tasks.every(t=>t.estimated_hours===4.5&&t.routine_position_id===null));
  assert.equal(new Set(tasks.map(t=>t.owner_id)).size,3);
  await card.getByRole('button',{name:'补生成本周任务'}).click();await page.locator('#actionConfirmSubmit').click();
  await page.waitForFunction(()=>!document.querySelector('#actionConfirmDialog').open);
  await page.waitForFunction(()=>Array.isArray(currentTasks));
  assert.equal((await page.evaluate(id=>currentTasks.filter(t=>t.parent_template_id===id),template.id)).length,3);
  await card.getByRole('button',{name:'编辑模板'}).click();
  assert.equal(await page.locator('#routineOwnerOptions input:checked').count(),3);
  await page.locator('#routineOwnerOptions input[value="'+config.newMember+'"]').check();
  await page.locator('#routineHours').fill('6');await page.locator('#routineForm button[type="submit"]').click();
  await page.locator('#routineDialog').waitFor({state:'hidden'});
  await page.waitForFunction(id=>window.routineTemplates.find(t=>t.id===id)?.estimated_hours===6,template.id);
  // Adding an explicitly selected person only backfills that employee.
  await card.getByRole('button',{name:'补生成本周任务'}).click();await page.locator('#actionConfirmSubmit').click();
  await page.waitForFunction(id=>currentTasks.filter(t=>t.parent_template_id===id).length===4,template.id);
  tasks=await page.evaluate(id=>currentTasks.filter(t=>t.parent_template_id===id),template.id);
  assert.equal(tasks.find(t=>t.owner_id===config.newMember).estimated_hours,6);
  assert(tasks.filter(t=>t.owner_id!==config.newMember).every(t=>t.estimated_hours===4.5));
  const mine=tasks.find(t=>t.owner_id===config.members[0]);
  await page.evaluate(async id=>{await setDemoActor(id);await load();await openPage('tasks');},mine.owner_id);
  await page.locator(`#taskPage button[onclick="reportRoutineHours(${mine.id})"]`).click();
  await page.locator('#actionInputValue').fill('3');await page.locator('#actionInputForm button[type="submit"]').click();
  await page.waitForFunction(id=>currentTasks.find(t=>t.id===id)?.actual_hours===3,mine.id);
  const unaffected=await (await page.request.get(config.base+'/api/tasks')).json();
  assert(unaffected.filter(t=>t.parent_template_id===template.id&&t.id!==mine.id).every(t=>t.actual_hours===0));
  await page.evaluate(id=>setDemoActor(id),config.manager);
  await page.locator('#orgTab').click();await page.locator('#orgPosition').waitFor({state:'visible'});
  await page.locator('#orgRoutineTab').click();await page.locator('#orgRoutine').waitFor({state:'visible'});
  await card.getByRole('button',{name:'停用',exact:true}).click();await page.locator('#actionConfirmSubmit').click();
  await page.waitForFunction(id=>!window.routineTemplates.some(t=>t.id===id),template.id);
  const after=await (await page.request.get(config.base+'/api/tasks')).json();
  assert.equal(after.filter(t=>t.parent_template_id===template.id).length,4);
  assert.deepEqual(errors,[]);assert(notices.some(s=>s.includes('已生成 3 条任务')));
  console.log('PASS: searchable employee multi-select, three independent tasks, repeat generation, selected employee backfill, hour snapshots, individual reporting, deactivation');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
